import YAML from 'yaml';
import type { TestPlan } from './plan';

/**
 * Writes the Promptfoo red-team configuration for one asset. The output is a normal
 * promptfooconfig.yaml: you can run it with Pertinax or straight with Promptfoo.
 */
export function toPromptfooConfig(plan: TestPlan): Record<string, unknown> {
  const { asset } = plan;
  const target = asset.target ?? { id: 'echo' };
  const config: Record<string, unknown> = {
    description: `Pertinax red team: ${asset.name}`,
    prompts: ['{{prompt}}'],
    targets: [{ label: asset.id, ...target }],
    redteam: {
      purpose: asset.purpose ?? asset.description ?? asset.name,
      numTests: plan.numTests,
      ...(asset.testing.attackProvider ? { provider: asset.testing.attackProvider } : {}),
      plugins: plan.plugins.map((p) => (p.config ? { id: p.id, config: p.config } : p.id)),
      strategies: plan.strategies.map((s) => ({ id: s })),
    },
    // Carried into every result so ingestion knows which asset a run belongs to.
    metadata: { pertinaxAsset: asset.id },
  };
  if (asset.testing.graderProvider) {
    config.defaultTest = { options: { provider: asset.testing.graderProvider } };
  }
  return config;
}

export function toPromptfooYaml(plan: TestPlan): string {
  const header = [
    `# Generated by Pertinax for asset "${plan.asset.id}". Regenerate instead of editing:`,
    `#   npm run pertinax -- generate ${plan.asset.id}`,
    `# Risks in scope: ${[...new Set(plan.plugins.flatMap((p) => p.risks))].sort().join(', ') || 'none'}`,
    ...(plan.skipped.length ? ['# Plugins left out:', ...plan.skipped.map((s) => `#   ${s.id}: ${s.reason}`)] : []),
    '',
  ]
    .filter((l) => l !== null)
    .join('\n');
  return header + YAML.stringify(toPromptfooConfig(plan), { lineWidth: 100 });
}
